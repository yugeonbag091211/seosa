#!/usr/bin/env node
/*
 * 검색 «부속» 가드 회귀 테스트 — 외부 호출 0회 / Supabase 접근 0회.
 *
 *   node scripts/test-search-type-guard.js
 *
 * ── 지켜야 할 것 한 줄 ────────────────────────────────────────────
 *
 *   마우스를 치면 마우스가 나온다. 마우스패드가 아니라.
 *   그리고 «어떤 경우에도» 진짜 상품이 사라지지 않는다.
 *
 * ── 이 테스트가 존재하는 이유 ─────────────────────────────────────
 *
 * 이 가드의 1차 구현은 _aiidentity 의 tier === MISMATCH 를 그대로 썼고,
 * 마우스·키보드에서 완벽하게 동작했다. 그러나 43개 품목 감사에서
 * 본품 86건 중 24건(28%)이 사라졌다 (2026-11-21).
 *
 *   "타이어" → 『금호 마제스티9 225/45R18』 사라짐 / 『타이어 공기압 게이지』 남음
 *   "커피"   → 『일리 클래시코 원두 250g』  사라짐 / 『커피 필터 드리퍼』     남음
 *
 * 정확히 거꾸로였다. tier 는 «제목에 검색어가 있나» 를 크게 보므로
 * 브랜드·모델명으로 파는 품목은 본품이 통째로 떨어진다. 마우스·키보드가
 * 잘 됐던 것은 그 품목의 제목이 거의 항상 검색어를 포함하기 때문이었다 —
 * 두 품목만 보고 일반화한 실수였다.
 *
 * 그래서 아래 §1 은 «부속이 빠지는가» 보다 «본품이 남는가» 를 먼저 본다.
 * 부속을 한둘 놓치는 것(미탐)보다 멀쩡한 상품이 사라지는 것(오탐)이
 * 훨씬 큰 사고다 — 사용자는 그 상품이 없는 줄 안다.
 *
 * ── 범위 ──────────────────────────────────────────────────────────
 *
 * 이 가드는 «부속» 만 걸러낸다. 강의·여행 서비스처럼 품목 자체가 다른
 * 것은 판매처 이름으로 거른다 (api/_adpick.js CONTENT_PLATFORM_PATTERN).
 * 제목만 보고 «다른 품목» 을 판정하는 일은 위 사고 때문에 하지 않는다.
 */
'use strict';

const { filterByProductType } = require('../api/_search-type-guard');

let pass = 0, fail = 0;
function check(ok, label, detail) {
  if (ok) { pass++; console.log(`  PASS  ${label}`); }
  else { fail++; console.log(`  FAIL  ${label}${detail === undefined ? '' : '  — ' + JSON.stringify(detail)}`); }
}
function section(name) { console.log(`\n${name}`); }

const items = titles => titles.map((t, i) => ({ title: t, lprice: 10000 + i * 1000 }));
const keptTitles = r => r.kept.map(x => x.title);

/* ================================================================== *
 *  §1  ★ 본품은 어떤 경우에도 사라지지 않는다 (오탐 0)
 *
 *  1차 구현이 깨뜨린 바로 그 품목들을 고정한다. 제목에 검색어가 한 번도
 *  나오지 않는 본품들이다 — 이것들이 살아남아야 가드를 켤 수 있다.
 * ================================================================== */
section('1. ★ 본품은 사라지지 않는다 — 제목에 검색어가 없는 상품들');

const MAIN_SURVIVES = [
  ['타이어', ['금호 마제스티9 225/45R18', '미쉐린 프라이머시4 205/55R16'], ['타이어 공기압 게이지']],
  ['커피',   ['일리 클래시코 원두 250g', '스타벅스 하우스블렌드 원두'],   ['커피 필터 드리퍼 100매']],
  ['시계',   ['세이코 프레사지 오토매틱', '카시오 지샥 GA-2100'],          ['시계 줄 메탈 밴드 20mm']],
  ['블랙박스', ['아이나비 QXD3000 2채널', '파인뷰 LX7000 플러스'],         ['블랙박스 메모리카드 128GB']],
  ['기타',   ['펜더 플레이어 스트라토캐스터', '콜트 어쿠스틱 AD810'],      ['기타 피크 셀룰로이드 10개']],
  ['전동드릴', ['보쉬 GSR 120-LI 전동드릴', '디월트 DCD777 브러시리스'],   ['드릴 비트 세트 10pcs']],
  ['선크림', ['라로슈포제 안쎌리오스 SPF50', '닥터지 레드블레미쉬 선크림'], ['선크림 퍼프 쿠션 교체용']],
  ['유모차', ['부가부 폭스5 디럭스 유모차', '스토케 익스플로리X'],          ['유모차 컵홀더 거치대']],
  ['텐트',   ['코베아 고스트 돔텐트 4인용', '스노우피크 랜드브리즈6'],      ['텐트 그라운드시트 방수포']],
  ['매트리스', ['시몬스 뷰티레스트 퀸 매트리스', '에이스침대 하이브리드 Q'], ['매트리스 커버 방수 토퍼']],
];

MAIN_SURVIVES.forEach(([q, main, noise]) => {
  const kept = keptTitles(filterByProductType(q, items([...main, ...noise]))).join(' ||| ');
  main.forEach(t => check(kept.includes(t), `"${q}" 본품 유지: ${t.slice(0, 30)}`, kept));
});

/* 어순 구제 — 「스탠드 선풍기」는 선풍기이고 「모니터 스탠드」는 모니터가 아니다. */
section('2. ★ 어순: 부속 낱말이 앞에 오면 본품이다');

const fan = keptTitles(filterByProductType('선풍기',
  items(['신일 20인치 스탠드 선풍기', '다이슨 쿨 타워팬', '선풍기 안전망 커버'])));
check(fan.some(t => /스탠드 선풍기/.test(t)), '「스탠드 선풍기」는 본품으로 남는다', fan);

const lamp = keptTitles(filterByProductType('조명',
  items(['필립스 휴 스탠드 조명', '루이스폴센 PH5 펜던트', '조명 갓 커버 쉐이드'])));
check(lamp.some(t => /스탠드 조명/.test(t)), '「스탠드 조명」은 본품으로 남는다', lamp);

const mon = keptTitles(filterByProductType('모니터',
  items(['삼성 오디세이 G5 27인치 모니터', 'LG 울트라기어 32인치 4K 모니터', '모니터 받침대 스탠드 우드'])));
check(!mon.some(t => /받침대/.test(t)), '「모니터 받침대 스탠드」는 부속으로 빠진다', mon);

/* ================================================================== *
 *  §3  부속이 실제로 빠진다
 * ================================================================== */
section('3. 부속이 빠진다');

function expectDropped(q, all, dropFrags) {
  const kept = keptTitles(filterByProductType(q, items(all))).join(' ||| ');
  dropFrags.forEach(f => check(!kept.includes(f), `"${q}" → 빠진다: ${f}`, kept));
}

expectDropped('마우스',
  ['로지텍 MX Master 3S 무선 마우스', '앱코 게이밍 마우스 유선', '마우스패드 장패드 데스크매트', '마우스 손목받침대 쿠션'],
  ['마우스패드', '손목받침대']);

expectDropped('키보드',
  ['한성 GK898B 기계식 키보드 적축', '로지텍 K380 무선 키보드', '키보드 덮개 실리콘 키스킨',
   '키보드 손목받침 팜레스트', '기계식 키보드 키캡 세트 PBT'],
  ['키스킨', '팜레스트', '키캡 세트']);

expectDropped('청소기',
  ['다이슨 V15 디텍트 무선청소기', '삼성 비스포크 제트 AI', '청소기 필터 교체용 호환', '청소기 브러시 헤드 부품'],
  ['필터 교체용', '브러시 헤드']);

expectDropped('스마트폰',
  ['삼성 갤럭시 S25 울트라 자급제', 'Apple 아이폰 16 Pro 256GB', '스마트폰 케이스 투명 범퍼', '스마트폰 강화유리 액정보호필름'],
  ['투명 범퍼', '액정보호필름']);

/*
 * 2026-11-26 — 판매자가 구체적 품목명 없이 "액세서리/부속품" 이라고만 써도
 * 빠져야 한다. 실사용에서 포착된 반례: "커피머신" 검색어는 붙여 썼는데
 * 제목은 "커피 머신" 으로 띄어 써서, 부속 낱말(액세서리)이 사전에 있어도
 * 검색어가 제목 어디에 닿는지(anchor)를 못 찾아 그냥 통과하고 있었다.
 */
expectDropped('커피머신',
  ['데롱기 ECAM350.15.B 마그니피카 S 전자동 커피머신',
   '[해외] 데롱기 ECAM 커피 머신 전 제품에 사용할 수 있는 물탱크 덮개 액세서리입니다.'],
  ['물탱크 덮개 액세서리']);

expectDropped('에어프라이어',
  ['필립스 에센셜 에어프라이어 HD9252', '쿠쿠 에어프라이어 전용 부속품 세트'],
  ['전용 부속품 세트']);

/* ================================================================== *
 *  §4  부속을 일부러 찾으면 부속이 남는다
 * ================================================================== */
section('4. 부속을 일부러 찾으면 남는다');

[
  ['마우스패드', ['마우스패드 장패드 게이밍', '스틸시리즈 QcK 마우스패드'], '마우스패드'],
  ['키보드 키캡', ['기계식 키보드 키캡 세트 PBT', '키캡 리무버 공구'], '키캡'],
  ['아이폰 케이스', ['아이폰16 프로 투명 범퍼 케이스', '아이폰 실리콘 케이스 정품'], '케이스'],
].forEach(([q, all, frag]) => {
  const kept = keptTitles(filterByProductType(q, items(all)));
  check(kept.length > 0 && kept.join(' ').includes(frag), `"${q}" → 부속이 남는다`, kept);
});

/* ================================================================== *
 *  §5  ★ 가드 때문에 결과가 0건이 되지 않는다
 * ================================================================== */
section('5. ★ 결과가 0건이 되지 않는다');

[
  ['마우스', ['마우스패드 장패드', '마우스 손목받침대', '마우스 클리너 브러쉬']],
  ['키보드', ['키보드 키스킨 커버', '키보드 손목받침 팜레스트']],
  ['에어팟', ['에어팟 케이스 실리콘', '에어팟 이어팁 교체용']],
  ['모니터', ['모니터 받침대 스탠드', '모니터 암 거치대']],
].forEach(([q, onlyNoise]) => {
  const r = filterByProductType(q, items(onlyNoise));
  check(r.kept.length > 0, `"${q}" 부속만 있어도 결과가 비지 않는다`, r.reason);
});

/*
 * 알려진 구멍: "노트북 가방" 은 '가방' 이 부속 어휘가 아니라
 * MAIN_PRODUCT_INTENT 로 잡혀, 슬리브·파우치 류가 빠진다.
 * 어휘에 '가방' 을 넣으면 가방 자체를 찾는 검색이 망가지므로 넣지 않았다.
 * 고정하는 것은 «결과가 비지 않는다» 와 «가방이 남는다» 까지다.
 */
const bag = filterByProductType('노트북 가방', items([
  '생활더봄 노트북 출장용 캐리어백팩', '삼성 갤럭시북6 노트북', 'targus 노트북 슬리브 파우치']));
check(bag.kept.length > 0, '「노트북 가방」 결과가 비지 않는다', keptTitles(bag));
check(keptTitles(bag).some(t => /캐리어백팩/.test(t)), '「노트북 가방」 가방이 남는다', keptTitles(bag));

/* ================================================================== *
 *  §6  입력 방어
 * ================================================================== */
section('6. 입력이 이상해도 터지지 않는다');

check(filterByProductType('마우스', []).kept.length === 0, '빈 목록');
check(filterByProductType('', items(['아무거나', '또 아무거나'])).applied === false, '빈 검색어면 판단하지 않는다');
check(filterByProductType('마우스', null).kept.length === 0, 'null 목록');
check(filterByProductType('마우스', items(['마우스 하나뿐'])).applied === false, '1건이면 비교하지 않는다');
check(filterByProductType('마우스', [{ title: null }, { title: undefined }]).kept.length === 2,
  '제목이 없어도 버리지 않는다');

/* ================================================================== *
 *  §7  전 카테고리 오탐 0 — 회귀 방지의 핵심
 * ================================================================== */
section('7. ★ 43개 품목 감사 요약 — 본품 오탐 0건');

const AUDIT = [
  ['모니터', ['삼성 오디세이 G5 27인치 모니터'], ['모니터 보호필름 블루라이트']],
  ['노트북', ['LG 그램 Pro 16Z95U 노트북'], ['노트북 파우치 슬리브 15.6']],
  ['프린터', ['HP 오피스젯 프로 9020 복합기'], ['프린터 잉크 카트리지 HP 호환']],
  ['이어폰', ['소니 WF-1000XM5 무선 이어폰'], ['이어폰 케이스 실리콘 커버']],
  ['TV', ['LG OLED 55인치 C4 TV'], ['TV 벽걸이 브라켓 거치대']],
  ['의자', ['시디즈 T50 메쉬 사무용 의자'], ['의자 바퀴 교체용 캐스터']],
  ['운동화', ['나이키 에어맥스 270 running'], ['운동화 끈 신발끈 120cm']],
  ['자전거', ['자이언트 에스케이프3 로드'], ['자전거 자물쇠 체인락']],
  ['골프채', ['타이틀리스트 T200 아이언 세트'], ['골프채 커버 헤드커버']],
  ['강아지사료', ['로얄캐닌 미니 어덜트 8kg'], ['사료 보관통 밀폐용기 10kg']],
  ['향수', ['조말론 라임바질앤만다린 100ml'], ['향수 공병 아토마이저 5ml']],
  ['기저귀', ['하기스 네이처메이드 4단계'], ['기저귀 휴지통 전용 리필']],
];
let lost = 0;
AUDIT.forEach(([q, main, noise]) => {
  const kept = keptTitles(filterByProductType(q, items([...main, ...noise])));
  main.forEach(t => { if (!kept.includes(t)) { lost++; console.log(`        ★ 사라짐: [${q}] ${t}`); } });
});
check(lost === 0, `감사 표본 ${AUDIT.length}개 품목에서 본품 손실 0건`, { lost });

/* ------------------------------------------------------------------ */
console.log('\n' + '='.repeat(66));
console.log(`검색 부속 가드 테스트:  ${pass} PASS / ${fail} FAIL`);
console.log('='.repeat(66));
process.exit(fail ? 1 : 0);
