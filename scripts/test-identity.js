#!/usr/bin/env node
/*
 * 동일상품 판정 규칙 테스트 — 외부 호출 0회 / DB 접근 0회.
 *
 *   node scripts/test-identity.js
 *
 * ── 왜 이 파일이 있는가 ─────────────────────────────────────────
 *
 * 2026-09-03 운영 감사에서 미수집 142개 중 57개가 "판매자가 새 product_id 로
 * 다시 올린" 상태였다. 제목이 거의 같은 다른 상품이 살아 있으니 이어붙이고
 * 싶어지는데, 실제로 규칙을 세 번 다듬는 동안 **매번 다른 오탐이 나왔다.**
 *
 * 아래 케이스는 전부 운영 데이터에서 실제로 걸린 것이다. 규칙을 느슨하게
 * 바꾸면 여기서 깨진다 — 그게 이 파일의 목적이다.
 *
 * ★ 이 규칙은 "연결해도 되는가" 를 판정할 뿐, 무엇도 자동으로 바꾸지 않는다.
 */
'use strict';

const {
  judgeSameProduct, modelCodes, years, grades, capacities, formats, colors, isBundle, normTitle
} = require('../api/_identity');

let pass = 0, fail = 0;
function check(ok, label, detail) {
  if (ok) { pass++; console.log(`  PASS  ${label}`); }
  else { fail++; console.log(`  FAIL  ${label}${detail === undefined ? '' : '  — ' + JSON.stringify(detail)}`); }
}
function section(n) { console.log(`\n${n}`); }
const tierOf = (a, b) => judgeSameProduct(a, b).tier;

console.log('=== 동일상품 판정 규칙 테스트 ===');

/* ================================================================
 *  1. 운영에서 실제로 걸린 오탐 — 전부 D 여야 한다
 * ================================================================ */
section('1. 실제 오탐 사례 (전부 "다른 상품" 이어야 한다)');
{
  check(tierOf(
    '(수입LP) Charlie Puth - Nine Track Mind',
    'Charlie Puth - Nine Track Mind [CD] [Deluxe]') === 'D',
    '★★ LP vs CD — 매체가 다르면 다른 상품');

  check(tierOf(
    '아픔이 길이 되려면 (김승섭)',
    '허무감에 압도될 때 지혜문학+아픔이 길이 되려면 세트') === 'D',
    '★★ 단품 vs 묶음 — 제목이 통째로 포함돼도 다른 상품');

  check(tierOf(
    '에이수스 2025 비보북 S 16 코어Ultra5 인텔 14세대',
    '에이수스 2026 비보북 16 코어Ultra5 인텔 14세대') === 'D',
    '★★ 연식이 다르면 다른 상품 (2025 ≠ 2026)');

  check(tierOf(
    '쿠쿠 정품 CRP-DHAS069FWM 전용 6인 이중모션 압력 고무패킹',
    '쿠쿠 정품 CRP-DHAS069FW 전용 6인 이중모션 압력 고무패킹') === 'D',
    '★★ 모델코드가 한 글자 다르면 다른 상품');

  check(tierOf(
    'LG전자 2025 그램 AI 16 코어Ultra5, 16Z90T-GA50K, 256GB',
    'LG전자 2025 그램 AI 17 코어Ultra5, 17Z90T-GA50K, 256GB') === 'D',
    '★★ 16인치 vs 17인치 — 모델코드가 다르다');

  check(tierOf(
    '아이패드 프로 11 256GB',
    '아이패드 프로 11 512GB') === 'D',
    '★★ 용량이 다르면 다른 상품');

  check(tierOf(
    '샥즈 오픈런 프로 2 골전도 이어폰',
    '샥즈 오픈런 2 골전도 이어폰') === 'D',
    '★★ Pro 유무는 등급 차이다');
}

/* ================================================================
 *  2. 옵션 단위가 다른 경우 — C (자동 연결 금지)
 * ================================================================ */
section('2. 옵션 단위가 다르면 C — 같은 상품이라도 자동 연결 금지');
{
  check(tierOf(
    '[샥즈 쿠팡 단독세트]샥즈 오픈런 프로 2 S820 골전도 이어폰, 오렌지-OR, S820',
    '[샥즈 쿠팡 단독세트]샥즈 오픈런 프로 2 S820 골전도 이어폰') === 'C',
    '★★ 우리는 색상 지정, 상대는 기본 상품 → C (vendorItemId 단위가 다르다)');

  check(tierOf(
    '아이리버 무선 이어폰 ITW-C1, WHITE',
    '아이리버 무선 이어폰 ITW-C1, 블랙') === 'C',
    '★ 색상이 서로 다르면 C');
}

/* ================================================================
 *  3. 정말 같은 상품 — A
 * ================================================================ */
section('3. 동일 확실 (A)');
{
  check(tierOf(
    '삼성노트북NT202B5C NT200B5C 호환 19V 어댑터',
    '삼성노트북NT202B5C NT200B5C 호환 19V 어댑터') === 'A',
    '★ 제목이 완전히 같다');

  check(tierOf(
    '봇치·더·록! 외전 히로이 키쿠리의 과음일기 4권세트',
    '봇치 더 록! 외전 히로이 키쿠리의 과음일기 4권세트') === 'A',
    '★★ 가운뎃점 같은 구두점만 다르면 같은 상품');

  /*
   * "1~4 - 4권세트" 와 "1~4권세트" 는 토큰이 실제로 다르다("4" 가 하나 더 있다).
   * 구두점 차이가 아니므로 A 가 아니라 B(동일 유력)로 떨어지는 것이 맞다 —
   * 사람이 확인할 목록에는 올라가되 "확실" 로 분류하지는 않는다.
   */
  check(tierOf(
    '봇치·더·록! 외전 히로이 키쿠리의 과음일기 1~4 - 4권세트',
    '봇치 더 록! 외전 히로이 키쿠리의 과음일기 1~4권세트') === 'B',
    '★ 토큰이 하나 더 있으면 A 가 아니라 B');

  check(tierOf(
    '한성컴퓨터 POLARIS2 유선 텐키리스 키보드 35g, PIXEL, TFG Magnetox 2XL',
    '한성컴퓨터 POLARIS2 유선 텐키리스 키보드 35g') === 'A',
    '★ 브랜드 + 모델코드가 같고 충돌 신호가 없다');

  check(normTitle('가 나 다') === normTitle('다 나 가'), '★ 어순만 다르면 같은 제목으로 본다');
}

/* ================================================================
 *  4. 신호 추출
 * ================================================================ */
section('4. 신호 추출');
{
  check(modelCodes('쿠쿠 CRP-DHAS069FWM 밥솥').has('CRP-DHAS069FWM'), '모델코드를 뽑는다');
  check(!modelCodes('닥터헤디슨 알로에 젤 500ml').has('500ML'), '★ 단위를 모델코드로 오인하지 않는다');
  check(years('에이수스 2025 비보북').has('2025'), '연식을 뽑는다');
  check(grades('아이폰 16 Pro').has('pro'), '등급(Pro)을 뽑는다');
  check(grades('아이패드 4세대').has('4세대'), '세대를 뽑는다');
  check(capacities('갤럭시탭 256GB 11인치').has('256gb'), '용량을 뽑는다');
  check(capacities('갤럭시탭 256GB 11인치').has('11인치'), '크기를 뽑는다');
  check(formats('(수입LP) 앨범').has('lp'), '매체(LP)를 뽑는다');
  check(colors('이어폰, 오렌지-OR').has('오렌지'), '★ 색상이 하이픈에 붙어 있어도 잡는다');
  check(isBundle('A+B 세트') && !isBundle('단품 이어폰'), '묶음 여부를 가린다');
}

/* ================================================================
 *  5. 안전 기본값
 * ================================================================ */
section('5. 안전 기본값');
{
  check(tierOf('', '무엇') === 'D', '빈 제목은 D');
  check(tierOf('무엇', '') === 'D', '상대가 빈 제목이면 D');
  check(tierOf(null, undefined) === 'D', 'null 안전');
  check(tierOf('전혀 다른 상품 하나', '완전히 무관한 물건 둘') === 'C',
    '★ 닮지 않은 것은 A/B 가 아니다');
  const r = judgeSameProduct('아이폰 16 Pro 256GB', '아이폰 16 256GB');
  check(r.tier === 'D' && r.reasons.length > 0, '★ 판정에는 항상 이유가 붙는다', r);
}

console.log(`\n결과: ${pass} PASS / ${fail} FAIL\n`);
process.exit(fail ? 1 : 0);

