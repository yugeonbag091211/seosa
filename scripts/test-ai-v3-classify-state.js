'use strict';
const assert = require('node:assert/strict');
const { classifyIntent } = require('../api/_ai-v3-classify');
const { encodeState, decodeState, updateState } = require('../api/_ai-v3-state');
(async () => {
  let calls = 0;
  const llm = async () => { calls++; return { category: 'E' }; };
  const knowledge = await classifyIntent('OLED와 LCD 차이점 설명해줘', {}, llm);
  assert.equal(knowledge.category, 'B'); assert.equal(calls, 0);
  const timing = await classifyIntent('요즘 에어팟 살만해?', {}, llm);
  assert.equal(timing.category, 'E'); assert.equal(timing.mode, 'search'); assert.equal(timing.priceLookup, true); assert.equal(calls, 1);
  const fallback = await classifyIntent('무슨 말이지?', {}, async () => { throw new Error('offline'); });
  assert.equal(fallback.classificationSource, 'fallback');
  process.env.AI_V3_STATE_SECRET = 'test-only-state-secret';
  const first = updateState(null, { cards: [{ productId: 'sku:123', title: '에어팟', price: 200000 }], lastQuery: '에어팟', lastPlan: { mode: 'recommend', query: '에어팟', maxPrice: 300000 }, userPreferences: { preferredBrands: ['애플'], budgetRange: { max: 300000 } } });
  const second = updateState(first, { userPreferences: { excludedItems: ['중고'] } });
  const token = encodeState(second);
  assert.ok(token.length < 4096);
  const restored = decodeState(token);
  assert.equal(restored.turnCount, 2); assert.equal(restored.lastPlan.query, '에어팟');
  assert.equal(restored.shownProducts[0].id, 'sku:123'); assert.deepEqual(restored.userPreferences.preferredBrands, ['애플']);
  assert.equal(restored.userPreferences.budgetRange.max, 300000); assert.deepEqual(restored.userPreferences.excludedItems, ['중고']);
  const [prefix, payload, sig] = token.split('.');
  const changed = (payload[0] === 'A' ? 'B' : 'A') + payload.slice(1);
  assert.equal(decodeState([prefix, changed, sig].join('.')), null);
  assert.equal(decodeState('x'.repeat(4097)), null);
  delete process.env.AI_V3_STATE_SECRET;
  delete process.env.AUTH_SECRET;
  delete process.env.SUPABASE_SECRET_KEY;
  assert.equal(encodeState(first), null); assert.equal(decodeState(token), null);
  console.log('v3 classifier/state tests passed');
})().catch(err => { console.error(err); process.exitCode = 1; });
