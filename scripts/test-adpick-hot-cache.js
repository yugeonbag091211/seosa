'use strict';
const assert = require('node:assert/strict');
const {createHotCache}=require('../api/_adpick-hot-cache');
let t=Date.parse('2026-11-01T05:00:00.000Z');
const cache=createHotCache({now:()=>t,ttlMs:20000,maxEntries:128});
let pass=0;
const query=(n)=>'상품 테스트 '+n;
const opts={source:'ai',limit:5};
for(let n=0;n<100;n++){
  const k=query(n), product={title:k,price:10000+n,commissionlink:'https://example.test/p/'+n};
  assert.equal(cache.put(k,opts,{from:'api',items:[product],error:null}),true);
  const read=cache.get(k,opts);
  assert.equal(read.from,'cache');
  assert.equal(read.items[0].title,k);
  assert.equal(read.items[0].price,10000+n);
  pass++;
}
assert.equal(cache.size(),100);pass++;
assert.equal(cache.get(query(0),{source:'ai',limit:6}),null,'cannot claim 6 results from a 5-result cache');pass++;
assert.equal(cache.get(query(0),{source:'collect',limit:5}),null,'collector never uses hot cache');pass++;
assert.equal(cache.get(query(0),{source:'ai',limit:5,forceRefresh:true}),null,'forced refresh bypass');pass++;
assert.equal(cache.get(query(0),{source:'ai',limit:5,useCache:false}),null,'no-cache bypass');pass++;
assert.equal(cache.put('error',opts,{from:'none',items:[{title:'false'}],error:'quota'}),false);pass++;
assert.equal(cache.put('old',opts,{from:'stale-cache',items:[{title:'stale'}]}),false);pass++;
assert.equal(cache.put('network',opts,{from:'api',items:[{title:'bad'}],blocked:true}),false);pass++;
const cached=cache.get(query(0),opts);
cached.items[0].title='mutated outside';
assert.equal(cache.get(query(0),opts).items[0].title,query(0),'defensive copy');pass++;
t+=20000;
assert.equal(cache.get(query(0),opts),null,'expired at 20s exactly');pass++;
const bounded=createHotCache({now:()=>t,ttlMs:20000,maxEntries:8});
for(let n=0;n<100;n++)bounded.put(query(n),opts,{from:'api',items:[{title:query(n)}]});
assert.equal(bounded.size(),8);pass++;
assert.equal(bounded.get(query(0),opts),null,'oldest was evicted');pass++;
assert.equal(bounded.get(query(99),opts).items[0].title,query(99));pass++;
let midnight=Date.parse('2026-11-01T14:59:59.000Z');
const day=createHotCache({now:()=>midnight,ttlMs:20000});
day.put('day',opts,{from:'api',items:[{title:'before midnight'}]});
midnight+=2000;
assert.equal(day.get('day',opts),null,'KST midnight invalidates hot cache');pass++;
console.log('ADPICK_HOT_CACHE_SUMMARY',JSON.stringify({uniqueKeywords:100,pass,fail:0,externalCalls:0,dbWrites:0}));
