-- ── 무엇을 고르는가 ────────────────────────────────────────────────
--
--  products 69,666행 가운데 «매일 가격을 다시 확인할 값이 있는» 행만.
--
--  2026-09-18 에 대량 seed 로 카탈로그가 2,500 → 69,666 으로 불었다.
--  그 6만여 행은 한 번 값을 적었을 뿐 사용자가 본 적도, 우리가 추적한 적도
--  없다. 전부 매일 갱신하려 들면 쿠팡 하루 예산(3,400회)이 첫 몇 %에서
--  마르고 수집률 지표도 무너진다.
--
--  그래서 두 갈래만 남긴다.
--
--    ① seed 폭증 이전부터 관측된 상품   (recorded_at < 2026-09-17)
--    ② 이후라도 «사람이 실제로 건드린» 경로로 관측된 상품
--       source ∈ (search, ai, cron, import)
--
--  ★ source = 'collect' 는 일부러 넣지 않는다. 넣으면 수집기가 자기 자신을
--    승격시켜서, 한 번 수집된 seed 상품이 영구히 대상이 된다 — 결국 6만 행
--    전체가 대상이 되어 위 문제로 되돌아간다.
--
-- ── 2026-09-20 실측 (전체 분류, 상호배타) ──────────────────────────
--
--    ELIGIBLE (이 함수의 결과)                     2,965
--    수집은 됐지만 승격되지 않음 (source=collect)  13,754
--    seed 뿐                                       52,942
--    이력이 아예 없음                                   5
--    ─────────────────────────────────────────────────────
--    합계                                          69,666  ✔ products 전체와 일치
--
-- ── 알려진 한계 (고치려면 별도 결정이 필요하다) ────────────────────
--
--  · 날짜 2026-09-17 이 상수로 박혀 있다. 시간이 지나도 움직이지 않으므로
--    ①의 모집단은 줄기만 하고 늘지 않는다. 대상을 늘리는 길은 ② 뿐이다.
--  · 위 13,754개는 수집기가 2026-09-19 에 «실제로 가격을 받아 온» 상품이다
--    (유효 가격 13,763행, 0원·음수 0건). 지금 규칙에서는 다시는 갱신되지
--    않으므로 그 값이 그대로 굳는다.
--  이 둘은 카탈로그 확대 정책의 문제이지 이 함수의 버그가 아니다.
--  바꿀 때는 쿠팡/ADPICK 호출 예산을 먼저 계산하고 바꿀 것.

-- ★ products 와 조인한다 — 카탈로그에 «지금 있는» 상품만 대상이다.
--   price_history 에는 카탈로그에서 사라진 상품의 이력이 남아 있다
--   (2026-09-20 실측: 조건은 맞지만 products 에 없는 키 878개).
--   그 행들을 대상으로 내보내면 수집기가 «상품 정보가 없는 키» 를 받아
--   검색어도 링크도 만들지 못한 채 미시도로 남긴다.
create or replace function collector_eligible_products()
returns table (product_id text, mall text)
language sql
stable
as $$
  select distinct h.product_id, h.mall
    from price_history h
    join products p
      on p.product_id = h.product_id
     and p.mall = h.mall
   where h.recorded_at < timestamptz '2026-09-17 00:00:00+00'
      or h.source in ('search', 'ai', 'cron', 'import')
$$;

-- PostgREST 스키마 캐시 갱신 (없으면 .rpc() 가 404 를 돌려준다)
notify pgrst, 'reload schema';

